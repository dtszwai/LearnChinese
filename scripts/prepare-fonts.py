"""Regenerate web fonts without changing the original font files.

Manual maintenance only; normal npm builds use the checked-in output.
Python dependencies: fonttools[woff]==4.67.0 (Brotli 1.2.0).
Run from any directory: python scripts/prepare-fonts.py
"""

import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "src/font"
OUTPUT = FONT_DIR / "web"
SOURCES = {"WenKai": "WenKai.ttf", "KaiTi": "KaiTi.woff2", "Zihun67": "Zihun67.ttf"}


def public_characters():
    files = list((ROOT / "docs").rglob("*.mdx")) + list((ROOT / "docs").rglob("*.md"))
    for folder in ("src/components", "src/pages", "src/theme"):
        files.extend(p for p in (ROOT / folder).rglob("*") if p.suffix in {".tsx", ".ts", ".js", ".md"})
    files.extend((ROOT / "src/data/Quiz").glob("*.json"))
    files.extend(ROOT / f"src/data/{name}.json" for name in ("author", "cheatsheet", "quotes"))
    files.append(ROOT / "docusaurus.config.ts")
    lessons = json.loads((ROOT / "src/data/Learn/index.json").read_text(encoding="utf-8"))
    files.extend(ROOT / f"src/data/Learn/{lesson['slug']}.json" for lesson in lessons.values() if lesson.get("published") is not False)
    # Private lessons and teaching sources are intentionally not inspected.
    characters = set(range(0x20, 0x7F))
    for file in files:
        characters.update(map(ord, file.read_text(encoding="utf-8")))
    return characters


def unicode_ranges(codepoints):
    ranges = []
    for point in sorted(codepoints):
        if ranges and ranges[-1][1] + 1 == point:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return ", ".join(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}" for start, end in ranges)


def main():
    OUTPUT.mkdir(exist_ok=True)
    characters = public_characters()
    css = ["// Generated by scripts/prepare-fonts.py. Keep original fonts for regeneration."]
    for family, filename in SOURCES.items():
        source = FONT_DIR / filename
        font = TTFont(source, recalcTimestamp=False)
        supported = set(font.getBestCmap())
        common = supported & characters
        # Keep the complete original face as a fallback for future/rare characters.
        if source.suffix == ".woff2":
            full_url = f"/src/font/{filename}"
        else:
            font.flavor = "woff2"
            full_file = OUTPUT / f"{family}-full.woff2"
            font.save(full_file)
            full_url = f"/src/font/web/{full_file.name}"
        options = subset.Options()
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        options.name_legacy = True
        options.notdef_outline = True
        options.glyph_names = True
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=common)
        subsetter.subset(font)
        font.flavor = "woff2"
        common_file = OUTPUT / f"{family}-common.woff2"
        font.save(common_file)
        assert set(TTFont(common_file).getBestCmap()) == common
        for url, points in ((full_url, supported - common), (f"/src/font/web/{common_file.name}", common)):
            if points:
                css.append(f'@font-face {{\n  font-family: {family};\n  src: url("{url}") format("woff2");\n  font-display: swap;\n  unicode-range: {unicode_ranges(points)};\n}}')
        print(f"{family}: {source.stat().st_size:,} -> {common_file.stat().st_size:,} bytes for {len(common)} common characters; all {len(supported)} characters retained across both faces")
    (ROOT / "src/css/_fonts.scss").write_text("\n\n".join(css) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
